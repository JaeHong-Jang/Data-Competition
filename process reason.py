"""
### 4-1. Fv/Fm 극한 스트레스 플래그
X['extreme_stress_fv'] = (X['Fv-Fm'] < 0.6).astype(int)

[왜 0.6 기준?]
- 문헌 근거: Fv/Fm < 0.6은 극한 스트레스 지표
- 정상 범위: 0.75~0.85 (건강한 식물)
- 0.6 이하: 광계II 심각 손상, 회복 어려움

[왜 제거하지 않고 플래그 처리?]
- 극한 상황도 중요한 정보
- 실제 기후변화 시나리오에서 발생 가능
- 모델이 극한 상황 패턴도 학습해야 함

### 4-2. 에너지 보존 법칙 검증
X['energy_check'] = abs(X['ABS-RC'] - (X['Tro-RC'] + X['Dio-RC']))

[왜 검증?]
- 물리 법칙: 흡수 에너지 = 활용 에너지 + 소산 에너지
- ABS = Tro + Dio (OJIP 분석법 기본 원리)
- 측정 오류 검출용

[결과]
- 위반 사례 0개 → 데이터 신뢰성 확인
"""

# ========================================
# STEP 5: Feature Engineering - 생물학적 의미
# ========================================

"""
### 5-1. 생장 단계 변수
growth_stage_map = {
    5: 'vegetative_early',   # 초기 영양생장
    6: 'vegetative_mid',     # 중기 영양생장  
    7: 'vegetative_late',    # 후기 영양생장
    8: 'reproductive',       # 생식생장
    9: 'senescence'         # 노화/수확기
}

[왜 생장 단계 구분?]
- 자료조사: 5-7월 영양생장, 8-9월 생식생장
- 시기별 생리적 특성 완전히 다름:
  * 5월: 활발한 잎 생장, 높은 엽록소
  * 6-7월: 최대 광합성 활성
  * 8월: 개화/결실로 자원 재분배
  * 9월: 지하부 양분 축적 (잎 기능 감소)

### 5-2. VPD 스트레스 (2.5 kPa 기준)
X['vpd_stress'] = (X['VPD'] > 2.5).astype(int)

[왜 2.5 kPa?]
- 자료조사: VPD 2.5 kPa 이상 시 미세털 보호 메커니즘 작동
- 천궁 잎 표면의 은녹색 미세털이 수분 손실 방어
- 경계층 형성 → 증산 억제 → 광 반사로 온도 하강

### 5-3. 온도 스트레스 (15-25°C 기준)
X['temp_optimal'] = ((X['Temp'] >= 15) & (X['Temp'] <= 25))
X['heat_stress'] = (X['Temp'] > 25)

[왜 이 범위?]
- 자료조사: 천궁 생육 적온 15-25°C
- 25°C 초과: 호흡 > 광합성, 순생산량 감소
- 15°C 미만: 효소 활성 저하, 성장 둔화

### 5-4. CO2 독성 (800ppm 기준)
X['co2_toxic'] = (X['CO2ppm'] > 800).astype(int)

[왜 800ppm?]
- 문헌 연구: 800ppm 이상에서 독성 효과 시작
- 기공 폐쇄 → 증산 감소 → 영양분 이동 저해
- 과도한 탄수화물 축적 → 피드백 억제

### 5-5. 복합 스트레스 지수
X['stress_index'] = (X['Temp'] - 20) * (X['CO2ppm'] - 432) / 432

[왜 이 공식?]
- 온도와 CO2의 상호작용 효과 표현
- 20°C: 천궁 최적 온도 중간값
- 432ppm: SSP1 기준 (현재 수준)
- 정규화(/432): 스케일 조정

### 5-6. SSP3 6월 이상 패턴
X['ssp3_june_anomaly'] = ((scenario == 'SSP3') & (month == 6))

[왜 SSP3 6월?]
- EDA 발견: SSP3 6월에 급격한 감소
- 원인 추정: 
  * 중간 수준 CO2(834ppm) + 고온 = 최악 조합
  * 광호흡 증가 + 불완전한 적응
  * SSP5는 오히려 극한 적응 메커니즘 발동

### 5-7. 9월 전환기
X['september_transition'] = (X['month'] == 9)

[왜 9월 특별 처리?]
- 자료조사: 9월은 생리적 대전환기
- 지상부 → 지하부 자원 재분배
- 광합성 의도적 감소 (80% 하락)
- 뿌리 저장 효율 1.9배 증가
- 월동 준비 전략 (다년생 식물 특성)

### 5-8. 에너지 효율 지표
X['energy_efficiency'] = X['Eto-RC'] / X['Tro-RC']
X['dissipation_ratio'] = X['Dio-RC'] / X['ABS-RC']

[왜 비율 계산?]
- 절대값보다 비율이 생리 상태 잘 반영
- energy_efficiency: 전자전달 효율성
- dissipation_ratio: 보호 메커니즘 활성도
"""

